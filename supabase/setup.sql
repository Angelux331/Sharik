-- Storage: crea un bucket público llamado portal-archivos en Storage > New bucket.
-- Luego ejecuta las políticas de Storage de abajo.
drop policy if exists "demo storage read" on storage.objects;
create policy "demo storage read" on storage.objects for select to anon, authenticated using (bucket_id = 'portal-archivos');
drop policy if exists "demo storage upload" on storage.objects;
create policy "demo storage upload" on storage.objects for insert to anon, authenticated with check (bucket_id = 'portal-archivos');
drop policy if exists "demo storage delete" on storage.objects;
create policy "demo storage delete" on storage.objects for delete to anon, authenticated using (bucket_id = 'portal-archivos');
