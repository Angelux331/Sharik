-- Ejecuta este archivo completo en Supabase > SQL Editor > New query.
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.files (
  id bigint generated by default as identity primary key,
  title text not null,
  category_id bigint not null references public.categories(id) on delete restrict,
  original_name text not null,
  storage_path text not null unique,
  public_url text not null,
  mime_type text not null,
  size bigint not null,
  created_at timestamptz not null default now()
);

alter table public.categories enable row level security;
alter table public.files enable row level security;

-- SOLO para demo/prototipo público: cualquier visitante puede leer y modificar.
-- No uses estas políticas para documentos internos, personales o confidenciales.
drop policy if exists "demo categories readable" on public.categories;
create policy "demo categories readable" on public.categories for select to anon, authenticated using (true);
drop policy if exists "demo categories insertable" on public.categories;
create policy "demo categories insertable" on public.categories for insert to anon, authenticated with check (true);
drop policy if exists "demo files readable" on public.files;
create policy "demo files readable" on public.files for select to anon, authenticated using (true);
drop policy if exists "demo files insertable" on public.files;
create policy "demo files insertable" on public.files for insert to anon, authenticated with check (true);
drop policy if exists "demo files deletable" on public.files;
create policy "demo files deletable" on public.files for delete to anon, authenticated using (true);

